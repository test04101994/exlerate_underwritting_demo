/**
 * Fetches the list of attachment filenames for a Jira ticket.
 * Tries the real Jira API first; falls back to scanning public/jira-documents/.
 */
export async function getJiraTicketAttachments(ticketKey: string): Promise<string[]> {
  // Try live Jira API
  if (jiraConfig) {
    try {
      const auth = Buffer.from(`${jiraConfig.username}:${jiraConfig.apiToken}`).toString('base64');
      const response = await axios.get(`${jiraConfig.baseUrl}/rest/api/2/issue/${ticketKey}`, {
        headers: { 'Authorization': `Basic ${auth}`, 'Accept': 'application/json' },
        params: { fields: 'attachment' },
        timeout: 8000,
      });
      const attachments: any[] = response.data?.fields?.attachment || [];
      if (attachments.length > 0) {
        console.log(`[getJiraTicketAttachments] Found ${attachments.length} attachment(s) for ${ticketKey} via API`);
        return attachments.map((a: any) => a.filename as string).filter(Boolean);
      }
    } catch (err: any) {
      console.warn(`[getJiraTicketAttachments] API call failed for ${ticketKey}:`, err.message);
    }
  }

  // Fallback: scan local jira-documents directory
  try {
    const { readdirSync, existsSync } = await import('fs');
    const { join } = await import('path');
    const dir = join(process.cwd(), 'public', 'jira-documents');
    if (existsSync(dir)) {
      const files = readdirSync(dir).filter(f =>
        f.endsWith('.pdf') || f.endsWith('.docx') || f.endsWith('.xlsx')
      );
      if (files.length > 0) {
        console.log(`[getJiraTicketAttachments] Fallback: found ${files.length} file(s) in jira-documents`);
        return files;
      }
    }
  } catch (err: any) {
    console.warn('[getJiraTicketAttachments] Filesystem fallback failed:', err.message);
  }

  return [];
}