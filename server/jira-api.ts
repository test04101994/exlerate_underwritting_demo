// Initialize Jira config from credential manager
async function initJiraConfig(): Promise<void> {
  try {
    console.log('[Jira API] Loading configuration from credentials.json...');
    const config = await credentialManager.getJiraCredentials();
    
    console.log('[Jira API] Raw config received:', {
      base_url: config.base_url,
      email: config.email,
      api_token: config.api_token ? 'PRESENT' : 'MISSING',
      project_key: config.project_key
    });
    
    jiraConfig = {
      baseUrl: config.base_url,
      username: config.email, // using email as username for Jira
      apiToken: config.api_token,
      projectKey: config.project_key || 'XSX', // Use project_key from JSON
      parentTask: config.parent_task || 'XSX-4113' // Add parent task support
    };
    
    console.log('[Jira API] Configuration loaded successfully:', {
      baseUrl: jiraConfig.baseUrl,
      username: jiraConfig.username,
      apiToken: jiraConfig.apiToken ? 'PRESENT' : 'MISSING',
      projectKey: jiraConfig.projectKey
    });
  } catch (error) {
    console.error('[Jira API] Failed to load configuration:', error);
    jiraConfig = null;
  }
}
