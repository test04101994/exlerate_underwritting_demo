  function registerCommentWatcher(ticketKey: string, sessionId: string, agentCommentId: string) {
    const watcherId = `${ticketKey}-${sessionId}`;
    const watcher: CommentWatcher = {
      ticketKey,
      sessionId,
      agentCommentId,
      lastChecked: new Date(),
      isActive: true
    };
    
    activeCommentWatchers.set(watcherId, watcher);
    console.log(`[Comment Watcher] Registered watcher for ticket ${ticketKey}, session ${sessionId}, comment ${agentCommentId}`);
    
    // Log active watchers count
    const activeCount = Array.from(activeCommentWatchers.values()).filter(w => w.isActive).length;
    console.log(`[Comment Watcher] Total active watchers: ${activeCount}`);
  }

