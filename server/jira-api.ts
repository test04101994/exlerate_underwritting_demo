// Comment watcher system
interface CommentWatcher {
  ticketKey: string;
  sessionId: string;
  agentCommentId: string;
  lastChecked: Date;
  isActive: boolean;
}

const activeCommentWatchers: Map<string, CommentWatcher> = new Map();

// Comment watcher functions
async function checkForNewComments(watcher: CommentWatcher): Promise<boolean> {
  try {
    if (!jiraConfig) return false;
    
    const auth = Buffer.from(`${jiraConfig.username}:${jiraConfig.apiToken}`).toString('base64');
    
    // Get ticket comments
    const response = await axios.get(`${jiraConfig.baseUrl}/rest/api/2/issue/${watcher.ticketKey}/comment`, {
      headers: {
        'Authorization': `Basic ${auth}`,
        'Accept': 'application/json'
      },
      timeout: 10000
    });

    const comments = response.data.comments || [];
    
    // Special handling for Communication Agent watcher (watches for ANY new human comment)
    if (watcher.agentCommentId === 'COMMUNICATION_WATCH') {
      const newHumanComments = comments.filter((comment: any) => {
        const commentDate = new Date(comment.created);
        const isAfterLastCheck = commentDate > watcher.lastChecked;
        const isNotBot = !comment.body?.includes('🤖') && 
                        !comment.body?.includes('AI-Generated') &&
                        !comment.body?.includes('*Generated by') &&
                        !comment.body?.includes('Mismatch Summary Agent') && 
                        !comment.body?.includes('Field Comparison Analysis');
        return isAfterLastCheck && isNotBot;
      });
      
      if (newHumanComments.length > 0) {
        console.log(`[Communication Watcher] ✅ Found ${newHumanComments.length} new human comments in ${watcher.ticketKey}`);
        newHumanComments.forEach((comment: any, index: number) => {
          console.log(`[New Comment ${index + 1}] Author: ${comment.author.displayName}, Created: ${comment.created}`);
          console.log(`[New Comment ${index + 1}] Body: ${comment.body.substring(0, 100)}...`);
        });
        return true;
      }
      return false;
    }
    
    // Original logic for Quality Assurance Agent watcher (watches for comments AFTER a specific agent comment)
    const agentCommentIndex = comments.findIndex((comment: any) => comment.id === watcher.agentCommentId);
    
    if (agentCommentIndex === -1) {
      console.log(`[Comment Watcher] Agent comment ${watcher.agentCommentId} not found in ${watcher.ticketKey}`);
      return false;
    }
    
    // Check if there are any comments after our agent comment
    const commentsAfterAgent = comments.slice(agentCommentIndex + 1);
    const newHumanComments = commentsAfterAgent.filter((comment: any) => {
      const commentDate = new Date(comment.created);
      const isAfterLastCheck = commentDate > watcher.lastChecked;
      const isNotBot = !comment.body.includes('Mismatch Summary Agent') && !comment.body.includes('Field Comparison Analysis');
      return isAfterLastCheck && isNotBot;
    });
    
    if (newHumanComments.length > 0) {
      console.log(`[Comment Watcher] Found ${newHumanComments.length} new human comments after agent comment in ${watcher.ticketKey}`);
      
      // Log the new comments for debugging
      newHumanComments.forEach((comment: any, index: number) => {
        console.log(`[New Comment ${index + 1}] Author: ${comment.author.displayName}, Created: ${comment.created}`);
        console.log(`[New Comment ${index + 1}] Body: ${comment.body.substring(0, 100)}...`);
      });
      
      return true;
    }
    
    return false;
  } catch (error: any) {
    console.error(`[Comment Watcher] Error checking comments for ${watcher.ticketKey}:`, error.message);
    return false;
  }
}

// Resume workflow when human response detected
async function resumeWorkflowFromWatcher(sessionId: string, ticketKey: string): Promise<void> {
  try {
    console.log(`[Comment Watcher] Human response detected in ${ticketKey} - resuming workflow ${sessionId}`);
    
    // Import resumeWorkflowAfterHumanResponse function from routes
    const routes = await import('./routes');
    if (routes.resumeWorkflowAfterHumanResponse) {
      await routes.resumeWorkflowAfterHumanResponse(sessionId);
    } else {
      console.error('[Comment Watcher] resumeWorkflowAfterHumanResponse function not found in routes');
    }
    
  } catch (error) {
    console.error(`[Comment Watcher] Error resuming workflow ${sessionId}:`, error);
  }
}


// Auto-polling system for Jira updates and comment watching
function startJiraPolling() {
  if (pollingInterval) {
    clearInterval(pollingInterval);
  }
  
  console.log('Starting Jira auto-polling system every 2 seconds');
  pollingInterval = setInterval(async () => {
    try {
      // Ensure Jira config is loaded before polling
      if (!jiraConfig) {
        await initJiraConfig();
      }
      
      if (!jiraConfig?.username || !jiraConfig?.apiToken) {
        return;
      }
      
      // Re-enabled polling with new token
      
      // Check for new comments on watched tickets
      const watcherEntries = Array.from(activeCommentWatchers.entries());
      for (const [watcherId, watcher] of watcherEntries) {
        if (!watcher.isActive) continue;
        
        const hasNewComments = await checkForNewComments(watcher);
        if (hasNewComments) {
          // Resume workflow and deactivate watcher
          await resumeWorkflowFromWatcher(watcher.sessionId, watcher.ticketKey);
          watcher.isActive = false;
          activeCommentWatchers.delete(watcherId);
        } else {
          // Update last checked time
          watcher.lastChecked = new Date();
        }
      }
      
      const auth = Buffer.from(`${jiraConfig.username}:${jiraConfig.apiToken}`).toString('base64');
      let jql = 'parent = "XSX-4113" ORDER BY updated DESC';
      
      const response = await axios.get(`${jiraConfig.baseUrl}/rest/api/3/search/jql`, {
        headers: {
          'Authorization': `Basic ${auth}`,
          'Accept': 'application/json',
        },
        params: {
          jql,
          fields: 'summary,description,status,priority,reporter,created,updated,duedate,project,issuetype,parent',
          maxResults: 50
        }
      });

      const tasks = response.data.issues.map((issue: any) => ({
        id: issue.id,
        key: issue.key,
        summary: issue.fields.summary || '',
        description: issue.fields.description || '',
        status: {
          name: issue.fields.status?.name || 'Unknown',
          category: issue.fields.status?.statusCategory?.name || 'To Do'
        },
        priority: {
          name: issue.fields.priority?.name || 'Medium',
          iconUrl: issue.fields.priority?.iconUrl || ''
        },
        reporter: {
          displayName: issue.fields.reporter?.displayName || 'Unknown',
          emailAddress: issue.fields.reporter?.emailAddress || ''
        },
        created: issue.fields.created,
        updated: issue.fields.updated,
        dueDate: issue.fields.duedate,
        project: {
          key: issue.fields.project?.key || '',
          name: issue.fields.project?.name || ''
        },
        issueType: {
          name: issue.fields.issuetype?.name || '',
          iconUrl: issue.fields.issuetype?.iconUrl || ''
        },
        parent: issue.fields.parent ? {
          key: issue.fields.parent.key,
          summary: issue.fields.parent.fields?.summary || ''
        } : null,
        url: `${jiraConfig?.baseUrl || 'https://digitalfx.atlassian.net'}/browse/${issue.key}`
      }));

      // Check if there are updates
      const latestUpdate = tasks.length > 0 ? tasks[0].updated : '';
      if (latestUpdate !== lastUpdateTime) {
        console.log(`Jira update detected at ${latestUpdate} - refreshing cache`);
        cachedTasks.length = 0;
        cachedTasks.push(...tasks);
        lastUpdateTime = latestUpdate;
      }
      
    } catch (error: any) {
      console.log('Auto-polling error:', error?.response?.data || error?.message || 'Unknown error');
    }
  }, 2000); // Poll every 2 seconds
}

